// Pont minimal et sûr entre la page et le processus principal.
const { contextBridge, ipcRenderer, webUtils, webFrame } = require('electron');

const inv = ch => (...a) => ipcRenderer.invoke(ch, ...a);
const on = ch => fn => ipcRenderer.on(ch, (_e, p) => fn(p));

contextBridge.exposeInMainWorld('kcNative', {
  openDialog: inv('open-dialog'),
  saveDialog: inv('save-dialog'),
  readText: inv('read-text'),
  writeFile: inv('write-file'),
  exists: inv('exists'),
  stat: inv('stat'),
  listDir: inv('list-dir'),
  places: inv('places'),
  getPending: inv('get-pending'),
  userData: inv('user-data'),
  defaultDir: inv('default-dir'),
  tempDir: inv('temp-dir'),
  removeDir: inv('remove-dir'),
  ffAvailable: inv('ff-available'),
  probe: inv('probe'),
  waveform: inv('waveform'),
  thumbs: inv('thumbs'),
  jobStart: inv('job-start'),
  jobCancel: inv('job-cancel'),
  proxyPath: inv('proxy-path'),
  proxyStart: inv('proxy-start'),
  keyInterval: inv('keyint'),
  encoders: inv('encoders'),
  aiStatus: inv('ai-status'),
  aiInstall: inv('ai-install'),
  aiStart: inv('ai-start'),
  aiCancel: inv('ai-cancel'),
  onAiInstallProgress: on('ai-install-progress'),
  onAiProgress: on('ai-progress'),
  onAiDone: on('ai-done'),
  cacheSize: inv('cache-size'),
  cacheClear: inv('cache-clear'),
  autosaveWrite: inv('autosave-write'),
  autosaveRead: inv('autosave-read'),
  autosaveClear: inv('autosave-clear'),
  listFonts: inv('list-fonts'),
  onJobProgress: on('job-progress'),
  onJobDone: on('job-done'),
  pathForFile: f => { try { return webUtils.getPathForFile(f); } catch { return null; } },
  confirmClose: () => ipcRenderer.send('confirm-close'),
  setTitle: t => ipcRenderer.send('set-title', t),
  setTitleBar: o => ipcRenderer.send('set-titlebar', o),
  toggleDevTools: () => ipcRenderer.send('toggle-devtools'),
  toggleFullscreen: () => ipcRenderer.send('toggle-fullscreen'),
  showInFolder: p => ipcRenderer.send('show-in-folder', p),
  openPath: p => ipcRenderer.send('open-path', p),
  onOpenPath: on('open-path'),
  onCloseRequest: fn => ipcRenderer.on('close-request', () => fn()),
  appVersion: inv('app-version'),
  updateState: inv('update-state'),
  updateCheck: inv('update-check'),
  updateDownload: inv('update-download'),
  updateInstall: () => ipcRenderer.send('update-install'),
  onUpdateStatus: on('update-status'),
  setZoom: f => webFrame.setZoomFactor(f),
});
